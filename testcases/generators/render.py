def marker() -> str:
    return f"<!-- generated by {GENERATOR_REL}; do not edit by hand - edit sources/ instead -->"


def anchor(cid: str) -> str:
    return "case-" + re.sub(r"[^a-z0-9]+", "-", cid.lower()).strip("-")


def cell(text) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def bullets(items) -> str:
    return "\n".join(f"- {item}" for item in items)


def numbers(items) -> str:
    return "\n".join(f"{index}. {item}" for index, item in enumerate(items, 1))


def json_block(obj) -> str:
    return json.dumps(obj, indent=2, ensure_ascii=False)


def suite_title(suite: str) -> str:
    layer = suite.split("/")[0]
    stem = suite.split("/")[-1][: -len(".md")]
    return f"{layer.capitalize()} - {stem.replace('-', ' ')}"


def requirement_line(token: str, inv: Inventory) -> str:
    meta = inv.requirement_meta(token) or {}
    must = " (MUST)" if meta.get("must") else ""
    return f"`{token}` - {meta.get('title', '')} (SRS section {meta.get('srs_section', '?')}{must})"


def facet_line(token: str, inv: Inventory) -> str:
    parsed = inv.facet_meta(token)
    if not parsed:
        return f"`{token}`"
    family, item = parsed
    group = f", {item['group']}" if item.get("group") else ""
    requires = item.get("requires") or []
    suffix = f" (requires {', '.join(sorted(requires))})" if requires else ""
    return (
        f"`{token}` - {item.get('title', '')} "
        f"[{family}{group}, SRS section {item.get('srs_section', '?')}]{suffix}"
    )


def case_block(case: dict, inv: Inventory, up: str) -> str:
    cid = case["id"]
    pair = case.get("pair") or "-"
    parts = [
        f'<a id="{anchor(cid)}"></a>',
        "",
        f"### `{cid}` - {case['title']}",
        "",
        "| Field | Value |",
        "|---|---|",
        f"| Suite | `{case['suite']}` |",
        f"| Layer | {case['layer']} |",
        f"| Environment | {case['environment']} |",
        f"| Priority | {case['priority']} |",
        f"| Gate | {case['gate']} |",
        f"| Basis | {case['basis']} |",
        f"| Pair | {('`' + pair + '`') if pair != '-' else '-'} |",
        f"| Source module | `sources/{case['_module']}.py` |",
        f"| Design status | `{DEFAULT_STATUS}` |",
        "",
    ]

    requirement_tokens = case.get("requirements") or []
    parts.append("**Provenance**")
    parts.append("")
    if requirement_tokens:
        parts.append("\n".join(f"- {requirement_line(token, inv)}" for token in requirement_tokens))
    else:
        parts.append("- no requirement ID declared (extension probe)")
    parts.append("")

    parts.append(f"**Real-life risk.** {case['risk']}")
    parts.append("")

    facet_tokens = case.get("facets") or []
    if facet_tokens:
        parts.append("**Coverage facets**")
        parts.append("")
        parts.append("\n".join(f"- {facet_line(token, inv)}" for token in facet_tokens))
        parts.append("")

    parts.append("**Preconditions**")
    parts.append("")
    parts.append(numbers(case["preconditions"]))
    parts.append("")

    parts.append("**Inputs** (synthetic test configuration, never production policy)")
    parts.append("")
    parts.append("```json")
    parts.append(json_block(case["inputs"]))
    parts.append("```")
    parts.append("")

    parts.append("**Steps**")
    parts.append("")
    parts.append("| # | Action | Expected |")
    parts.append("|---|---|---|")
    for index, step in enumerate(case["steps"], 1):
        parts.append(f"| {index} | {cell(step['action'])} | {cell(step['expected'])} |")
    parts.append("")

    for label, key in (
        ("Assertions", "assertions"),
        ("Forbidden", "forbidden"),
        ("Evidence to collect (redacted)", "evidence"),
        ("Cleanup", "cleanup"),
    ):
        parts.append(f"**{label}**")
        parts.append("")
        parts.append(bullets(case[key]))
        parts.append("")

    parts.append(f"**Automation seam.** {case['automation']}")
    parts.append("")

    parts.append("**Prerequisites**")
    parts.append("")
    prerequisites = case.get("prerequisites") or []
    parts.append(bullets(prerequisites) if prerequisites else "- none beyond the offline toolchain")
    parts.append("")

    parts.append("**References**")
    parts.append("")
    parts.append(bullets(f"`{reference}`" for reference in case["references"]))
    parts.append("")

    fixtures = case.get("fixtures") or []
    parts.append("**Fixtures**")
    parts.append("")
    parts.append(
        bullets(f"[`{fixture}`]({up}{fixture})" for fixture in fixtures) if fixtures else "- none"
    )
    parts.append("")

    parts.append(
        "**Status.** `"
        + DEFAULT_STATUS
        + "` - descriptive acceptance specification; the repository runtime is not exercised by this generated document, so nothing here has been executed. Machine-readable copy: "
        f"[`{up}{SCENARIO_DIR}/{cid}.json`]({up}{SCENARIO_DIR}/{cid}.json)."
    )
    parts.append("")
    return "\n".join(parts)


def render_suite(suite: str, cases: list, inv: Inventory) -> str:
    up = "../" * (len(suite.split("/")) - 1)
    layer = suite.split("/")[0]
    lines = [
        marker(),
        "",
        f"# {suite_title(suite)}",
        "",
        f"`{suite}` - layer `{layer}` - {len(cases)} case(s) - design status `{DEFAULT_STATUS}` throughout.",
        "",
        "Generated from " + ", ".join(f"`sources/{name}.py`" for name in MODULES) + ". "
        "Do not edit this file: change the source module and re-run `python testcases/_generate.py`.",
        "",
        "## Case index",
        "",
        "| Case ID | Environment | Priority | Gate | Title |",
        "|---|---|---|---|---|",
    ]
    for case in cases:
        lines.append(
            f"| [`{case['id']}`](#{anchor(case['id'])}) | {case['environment']} | {case['priority']} "
            f"| {case['gate']} | {cell(case['title'])} |"
        )
    lines.extend(["", "## Cases", ""])
    for case in cases:
        lines.append(case_block(case, inv, up))
    return "\n".join(lines).rstrip() + "\n"


