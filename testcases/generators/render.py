def render_traceability(cases: list, inv: Inventory, baseline_info: dict, pairs: dict) -> str:
    by_id = {case["id"]: case for case in cases if isinstance(case.get("id"), str)}
    lines = [
        marker(),
        "",
        "# Traceability - case index",
        "",
        f"{len(cases)} cases, every ID taken verbatim from the source modules (mixed case and dots preserved; "
        "no ID normalisation anywhere). One row per case; the reverse direction is in "
        "[`COVERAGE.md`](COVERAGE.md). Nothing in this file is evidence of execution: the repository "
        f"runtime is not exercised by generation and every case stays `{DEFAULT_STATUS}`.",
        "",
        "## Baseline preservation",
        "",
        f"- Current baseline: {baseline_info['count']} case IDs from "
        f"[`{BASELINE_REL}`]({BASELINE_REL}) (a snapshot taken before this generation).",
        f"- Preserved exactly once: {baseline_info['preserved']}. Missing: "
        f"{len(baseline_info['missing'])}. Duplicated: {len(baseline_info['duplicated'])}.",
        f"- New descriptive case IDs added by this generation: {len(baseline_info['new_case_ids'])}.",
        "- Every baseline ID below resolves to a case document; IDs are matched as exact strings, so "
        "`E2E-LIVE-001` is never satisfied by `E2E-LIVE-0010` and `INT-FR-CS-001-OTHERS` is never satisfied "
        "by `INT-FR-CS-001-OTHER`.",
        "- An older draft of this suite mentioned 343 IDs. That set cannot be recovered or verified from the "
        "repository, so this document claims only the current baseline snapshot; no historic ID is invented "
        "and no unavailable set is claimed as preserved.",
        "",
        "## Baseline ID placement",
        "",
        "| Baseline case ID | Suite | Layer | Environment |",
        "|---|---|---|---|",
    ]
    for cid in baseline_info.get("order") or sorted(by_id):
        case = by_id.get(cid)
        if case is None:
            lines.append(f"| `{cid}` | **MISSING - no case produces this ID** | - | - |")
            continue
        lines.append(
            f"| [`{cid}`]({case['suite']}#{anchor(cid)}) | `{case['suite']}` | {case['layer']} "
            f"| {case['environment']} |"
        )

    lines.extend(
        [
            "",
            "## Cases",
            "",
            "| Case ID | Suite | Layer | Env | Priority | Gate | Basis | Pair | Requirements | Facets |",
            "|---|---|---|---|---|---|---|---|---|---|",
        ]
    )
    for case in sorted(cases, key=lambda item: (item["suite"], item["id"])):
        requirements = case.get("requirements") or []
        facets = case.get("facets") or []
        pair = case.get("pair") or "-"
        lines.append(
            f"| [`{case['id']}`]({case['suite']}#{anchor(case['id'])}) | `{case['suite']}` "
            f"| {case['layer']} | {case['environment']} | {case['priority']} | {case['gate']} "
            f"| {case['basis']} | {('`' + pair + '`') if pair != '-' else '-'} "
            f"| {cell(', '.join(f'`{token}`' for token in requirements)) or '-'} "
            f"| {cell(', '.join(f'`{token}`' for token in facets)) or '-'} |"
        )

    lines.extend(
        [
            "",
            "## Offline/live pairing",
            "",
            f"{pairs['paired_e2e_cases']}/{pairs['e2e_cases']} e2e case(s) declare a counterpart; the partner "
            "must be an e2e case in the opposite environment, must point back, and must declare the same "
            f"requirements and facets. Unsymmetrical pair relations: {len(pairs['asymmetric'])}. "
            f"Unpaired e2e cases: {len(pairs['unpaired'])}.",
            "",
            "| E2E case | Counterpart |",
            "|---|---|",
        ]
    )
    for cid, partner in sorted((pairs.get("relations") or {}).items()):
        lines.append(f"| `{cid}` | `{partner}` |")

    lines.extend(
        [
            "",
            "## Documents",
            "",
            "| Suite | Layer | Cases |",
            "|---|---|---|",
        ]
    )
    per_suite = Counter(case["suite"] for case in cases)
    for suite in sorted(per_suite):
        lines.append(f"| [`{suite}`]({suite}) | {suite.split('/')[0]} | {per_suite[suite]} |")
    lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def render_coverage(inv: Inventory, cases: list, coverage: dict, both_env: dict) -> str:
    requirement_cases = coverage["requirement_cases"]
    facet_cases = coverage["facet_cases"]
    lines = [
        marker(),
        "",
        "# Coverage - reverse map",
        "",
        "Membership below is **exact token set membership**, never substring matching: a case covers `SRS-02` "
        "only if it declares `SRS-02`, and `TC-E2E-001` is never satisfied by `TC-E2E-0010`. Coverage is a "
        "traceability statement about specifications, not evidence that anything has been executed: every case "
        f"is `{DEFAULT_STATUS}`.",
        "",
        "## Requirement reverse map",
        "",
        "| Requirement | Kind | Cases | Case IDs |",
        "|---|---|---|---|",
    ]
    for token in sorted(inv.requirements):
        meta = inv.requirements[token]
        ids = requirement_cases.get(token, [])
        listed = ", ".join(f"`{cid}`" for cid in ids) if ids else "**GAP - no case claims this requirement**"
        lines.append(f"| `{token}` | {meta.get('kind', '')} | {len(ids)} | {listed} |")
    lines.extend(["", "## Section aliases", "", "| Alias | Cases | Case IDs |", "|---|---|---|"])
    for token in sorted(inv.aliases):
        ids = requirement_cases.get(token, [])
        listed = ", ".join(f"`{cid}`" for cid in ids) if ids else "**GAP - no case claims this section obligation**"
        lines.append(f"| `{token}` | {len(ids)} | {listed} |")

    lines.extend(["", "## Facet coverage", ""])
    for family in sorted(inv.facets):
        spec = inv.facets[family]
        tokens = sorted(spec["items"])
        covered = sum(1 for token in tokens if facet_cases.get(f"{family}:{token}"))
        lines.append(f"### {family} - {covered}/{len(tokens)} covered")
        lines.append("")
        lines.append(f"{spec['description']} (SRS section {spec['srs_section']}.)")
        lines.append("")
        lines.append("| Token | Requires | Cases | Case IDs |")
        lines.append("|---|---|---|---|")
        for token in tokens:
            full = f"{family}:{token}"
            item = spec["items"][token]
            ids = facet_cases.get(full, [])
            listed = ", ".join(f"`{cid}`" for cid in ids) if ids else "**GAP**"
            requires = ", ".join(f"`{req}`" for req in (item.get("requires") or [])) or "-"
            lines.append(f"| `{token}` | {requires} | {len(ids)} | {listed} |")
        lines.append("")

    lines.extend(
        [
            "## Both environments (system acceptance criteria and pilots)",
            "",
            "| Criterion | Offline e2e cases | Live e2e cases |",
            "|---|---|---|",
        ]
    )
    for token in sorted(both_env):
        entry = both_env[token]
        offline = ", ".join(f"`{cid}`" for cid in entry["offline"]) or "**GAP**"
        live = ", ".join(f"`{cid}`" for cid in entry["live"]) or "**GAP**"
        lines.append(f"| `{token}` | {offline} | {live} |")

    lines.extend(["", "## Remaining gaps", ""])
    if coverage["facet_gaps"]:
        lines.append("Mandatory facet tokens with no case (these are hard errors and must be empty):")
        lines.append("")
        lines.extend(f"- `{token}`" for token in coverage["facet_gaps"])
    else:
        lines.append("- No mandatory facet token is uncovered.")
    lines.append("")
    if coverage["requirement_gaps"]:
        lines.append(
            "Requirement or alias tokens with no case (reported, not fatal: a token may be carried by a "
            "section-level obligation or be planned for a later gate):"
        )
        lines.append("")
        lines.extend(f"- `{token}`" for token in coverage["requirement_gaps"])
    else:
        lines.append("- Every requirement ID and section alias is claimed by at least one case.")
    lines.extend(
        [
            "",
            "## Design status",
            "",
            f"- Total cases: {len(cases)}. Every case is `{DEFAULT_STATUS}`: the specifications exist, the "
            "system under test does not.",
            "- Gaps above are documented rather than hidden. They are not evidence of coverage and not a claim "
            "that the checklist surface is exhaustively covered.",
            "",
            "## Related maps",
            "",
            f"- [`{PLATFORM_KNOWLEDGE_DOC}`]({PLATFORM_KNOWLEDGE_DOC}) - knowledge base (section 10) and AI "
            "memory (section 16) tokens with their covering cases.",
            f"- [`{PLATFORM_ENTITIES_DOC}`]({PLATFORM_ENTITIES_DOC}) - canonical entity (section 14) tokens "
            "with their covering cases.",
            "- [`TRACEABILITY.md`](TRACEABILITY.md) - the forward direction: every case with its suite, "
            "environment, pair and tokens.",
            "- [`manifest.json`](manifest.json) - the same counts, the coverage gaps and the SHA-256 of every "
            "generator input in machine-readable form.",
            "",
        ]
    )
    return "\n".join(lines).rstrip() + "\n"


