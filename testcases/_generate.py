class Inventory:
    """Requirement IDs, section aliases and mandatory facet tokens from requirements.json."""

    def __init__(self, doc: dict) -> None:
        self.doc = doc
        self.requirements: dict[str, dict] = dict(doc.get("requirements") or {})
        self.aliases: dict[str, dict] = dict(doc.get("aliases") or {})
        self.facets: dict[str, dict] = {}
        for family, spec in (doc.get("facets") or {}).items():
            items = {}
            for item in spec.get("items") or []:
                token = item.get("token")
                if not isinstance(token, str) or not token:
                    raise GenerateError(
                        f"requirements.json: facet family '{family}' has an item without a token"
                    )
                items[token] = item
            self.facets[family] = {
                "description": spec.get("description", ""),
                "srs_section": spec.get("srs_section", ""),
                "mandatory": bool(spec.get("mandatory", True)),
                "items": items,
            }

    def requirement_meta(self, token: str):
        return self.requirements.get(token) or self.aliases.get(token)

    def facet_meta(self, token: str):
        family, sep, value = token.partition(":")
        if not sep:
            return None
        family_spec = self.facets.get(family)
        if family_spec is None:
            return None
        item = family_spec["items"].get(value)
        if item is None:
            return None
        return family, item

    def requirement_tokens(self) -> list:
        return sorted(list(self.requirements) + list(self.aliases))

    def mandatory_facet_tokens(self) -> list:
        tokens = []
        for family in sorted(self.facets):
            spec = self.facets[family]
            if spec["mandatory"]:
                tokens.extend(f"{family}:{value}" for value in sorted(spec["items"]))
        return tokens

    def facet_tokens(self) -> list:
        return sorted(
            f"{family}:{value}" for family, spec in self.facets.items() for value in spec["items"]
        )


def sha256_file(rel: str) -> str:
    """Deterministic content hash of a repository file, or 'missing' when absent."""
    path = REPO / rel
    if not path.is_file():
        return "missing"
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for chunk in iter(lambda: handle.read(65536), b""):
            digest.update(chunk)
    return digest.hexdigest()


def input_hashes() -> OrderedDict:
    """Pin every generator input (SRS, inventory, baseline, module sources) by SHA-256."""
    hashes: OrderedDict = OrderedDict()
    for rel in HASHED_INPUTS:
        hashes[rel] = sha256_file(rel)
    for name in MODULES:
        rel = f"testcases/sources/{name}.py"
        hashes[rel] = sha256_file(rel)
    return hashes


def load_inventory() -> Inventory:
    path = HERE / REQUIREMENTS_REL
    if not path.is_file():
        raise GenerateError(f"missing requirement inventory: testcases/{REQUIREMENTS_REL}")
    try:
        doc = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise GenerateError(f"testcases/{REQUIREMENTS_REL} is not valid JSON: {exc}") from exc
    if not isinstance(doc, dict):
        raise GenerateError(f"testcases/{REQUIREMENTS_REL} must contain a JSON object")
    inventory = Inventory(doc)
    if not inventory.requirements:
        raise GenerateError(f"testcases/{REQUIREMENTS_REL} declares no requirements")
    if not inventory.facets:
        raise GenerateError(f"testcases/{REQUIREMENTS_REL} declares no facet families")
    return inventory


def load_baseline() -> list:
    path = HERE / BASELINE_REL
    if not path.is_file():
        raise GenerateError(f"missing baseline ID snapshot: testcases/{BASELINE_REL}")
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise GenerateError(f"testcases/{BASELINE_REL} is not valid JSON: {exc}") from exc
    if not isinstance(data, list) or not all(isinstance(item, str) for item in data):
        raise GenerateError(f"testcases/{BASELINE_REL} must be a JSON array of case ID strings")
    return data


