def build_outputs(cases, fixtures, inv, baseline_info, coverage, pairs, both_env, problems, fixture_owners_map):
    outputs: OrderedDict = OrderedDict()

    suites: dict = {}
    for case in sorted(cases, key=lambda item: (item["suite"], item["id"])):
        suites.setdefault(case["suite"], []).append(case)

    documents = []
    for suite in sorted(suites):
        outputs[suite] = render_suite(suite, suites[suite], inv)
        documents.append({"path": suite, "cases": len(suites[suite]), "layer": suite.split("/")[0]})

    outputs["README.md"] = render_readme(inv, cases, fixtures, baseline_info, coverage)
    outputs["TRACEABILITY.md"] = render_traceability(cases, inv, baseline_info, pairs)
    outputs["COVERAGE.md"] = render_coverage(inv, cases, coverage, both_env)
    outputs[PLATFORM_KNOWLEDGE_DOC] = render_platform_knowledge_memory(inv, cases, coverage)
    outputs[PLATFORM_ENTITIES_DOC] = render_platform_entities(inv, cases, coverage)

    for path, data in sorted(fixtures.items()):
        outputs[path] = json.dumps(data, indent=2, ensure_ascii=False) + "\n"

    outputs[FIXTURES_GUIDE] = render_fixtures_guide(fixture_owners_map)
    outputs[LIVE_FIXTURES_GUIDE] = render_live_guide()
    outputs[LIVE_ENV_EXAMPLE] = render_env_example()

    for case in sorted(cases, key=lambda item: item["id"]):
        outputs[f"{SCENARIO_DIR}/{case['id']}.json"] = json.dumps(
            scenario_record(case), indent=2, ensure_ascii=False
        ) + "\n"

    outputs["manifest.json"] = render_manifest(
        inv,
        cases,
        fixtures,
        fixture_owners_map,
        baseline_info,
        coverage,
        pairs,
        both_env,
        problems,
        documents,
    )
    assert_output_paths(outputs)
    return outputs


def assert_output_paths(outputs: dict) -> None:
    """Refuse any output that would leave testcases/ or overwrite a hand-written input."""
    for rel in outputs:
        if rel.startswith("/") or ".." in rel.split("/") or rel.endswith("/"):
            raise GenerateError(f"generated path escapes testcases/: {rel!r}")
        if rel.replace("\\", "/") in SOURCE_OWNED:
            raise GenerateError(
                f"generated path {rel!r} collides with a hand-written input; the generator never "
                "rewrites its own sources"
            )
        if is_protected(rel):
            raise GenerateError(f"generated path {rel!r} is protected (local env, results or secrets)")


def stale_extras(outputs: dict) -> list:
    """Generated-looking files on disk that this run does not produce (never deleted by us)."""
    stale = []
    for directory, pattern in (
        ("fixtures/offline", "*.json"),
        (SCENARIO_DIR, "*.json"),
        ("fixtures/live", "*.json"),
        (PLATFORM_DIR, "*.md"),
        (".", "*.md"),
        (".", "*.tmp"),
    ):
        base = HERE / directory
        if not base.is_dir():
            continue
        for path in sorted(base.glob(pattern)):
            if not path.is_file():
                continue
            rel = path.relative_to(HERE).as_posix()
            if rel in outputs:
                continue
            if is_protected(rel):
                continue
            stale.append(rel)
    for layer in LAYER_DIRS:
        base = HERE / layer
        if not base.is_dir():
            continue
        for path in sorted(base.rglob("*.md")):
            rel = path.relative_to(HERE).as_posix()
            if rel not in outputs:
                stale.append(rel)
    return stale


def check_outputs(outputs: dict) -> int:
    """Compare generated content (case docs, fixtures, manifest, derived maps) with disk."""
    drift = []
    matched = 0
    for rel in sorted(outputs):
        path = HERE / rel
        if not path.is_file():
            drift.append(f"missing generated output: testcases/{rel}")
        elif path.read_text(encoding="utf-8") != outputs[rel]:
            drift.append(f"stale generated output (content differs from sources): testcases/{rel}")
        else:
            matched += 1
    for rel in stale_extras(outputs):
        drift.append(f"unexpected generated file that this generator does not produce: testcases/{rel}")
    if drift:
        for item in drift:
            print(f"STALE: {item}")
        print(
            f"FAILED: {len(drift)} generated file(s) out of date or unexpected "
            f"({matched} matched); run python testcases/_generate.py"
        )
        return 3
    print(
        f"OK: {len(outputs)} generated file(s) match the sources byte for byte, "
        f"including manifest.json and its input hashes"
    )
    return 0


def write_outputs(outputs: dict) -> list:
    """Atomically replace each generated file. All validation has already passed."""
    written = []
    for rel in sorted(outputs):
        if is_protected(rel):
            raise GenerateError(f"refusing to write protected path: testcases/{rel}")
        path = HERE / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        temporary = path.with_name(path.name + ".tmp")
        try:
            with open(temporary, "w", encoding="utf-8", newline="\n") as handle:
                handle.write(outputs[rel])
            os.replace(temporary, path)
        except OSError as exc:
            if temporary.exists():
                temporary.unlink()
            raise GenerateError(f"cannot write testcases/{rel}: {exc}") from exc
        written.append(rel)
    return written


def fixture_owners(modules: dict) -> dict:
    owners: dict = {}
    for name in MODULES:
        raw = getattr(modules[name], "FIXTURES", None)
        if isinstance(raw, dict):
            for key in raw:
                owners.setdefault(str(key), f"sources/{name}.py")
    return OrderedDict(sorted(owners.items()))


def report(problems: Problems) -> None:
    for warning in problems.warnings:
        print(f"WARN: {warning}")
    for error in problems.errors:
        print(f"ERROR: {error}")
    print(f"validation: {len(problems.errors)} error(s), {len(problems.warnings)} warning(s)")


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        prog="python testcases/_generate.py",
        description="Validate the testcase sources and generate the testcases documents, fixtures and manifest.",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="validate and compare generated output with disk; write nothing",
    )
    args = parser.parse_args(argv)

    problems = Problems()
    try:
        inv = load_inventory()
        baseline = load_baseline()
        modules = load_modules()
    except GenerateError as exc:
        print(f"ERROR: {exc}")
        return 2

    cases = collect_cases(modules, problems)
    fixtures = collect_fixtures(modules, problems)

    fixture_paths = set(fixtures) | {LIVE_ENV_EXAMPLE, FIXTURES_GUIDE, LIVE_FIXTURES_GUIDE}
    for case in cases:
        validate_case(case, problems, inv, fixture_paths)

    by_id = validate_ids(cases, problems)
    baseline_info = validate_baseline(cases, baseline, problems)
    pairs = validate_pairs(cases, by_id, problems)
    both_env = validate_both_environments(cases, inv, problems)
    coverage = build_coverage(cases, inv)

    for token in coverage["facet_gaps"]:
        problems.error(f"mandatory facet token {token!r} is not covered by any case")
    for token in coverage["requirement_gaps"]:
        problems.warn(f"requirement token {token!r} is not claimed by any case (reported as a coverage gap)")

    report(problems)
    if not problems.ok:
        print(
            f"FAILED: {len(problems.errors)} validation error(s); nothing was written and no generated "
            "file was touched"
        )
        return 2

    summary = [
        f"cases: {len(cases)} from {len(modules)} source module(s) "
        f"({', '.join(f'sources/{name}.py' for name in MODULES)})",
        "layers: " + ", ".join(f"{layer} {sum(1 for c in cases if c['layer'] == layer)}" for layer in LAYER_DIRS),
        "environments: " + ", ".join(
            f"{env} {sum(1 for c in cases if c['environment'] == env)}" for env in ENVIRONMENTS
        ),
        f"baseline: {baseline_info['preserved']}/{baseline_info['count']} current IDs preserved exactly once"
        f" (+{baseline_info['new_case_count']} new descriptive IDs)",
        f"e2e pairs: {pairs['paired_e2e_cases']}/{pairs['e2e_cases']} paired offline/live",
        f"coverage: requirements {sum(1 for ids in coverage['requirement_cases'].values() if ids)}"
        f"/{len(coverage['requirement_cases'])}, facets "
        f"{sum(1 for ids in coverage['facet_cases'].values() if ids)}/{len(coverage['facet_cases'])}",
    ]

    outputs = build_outputs(
        cases,
        fixtures,
        inv,
        baseline_info,
        coverage,
        pairs,
        both_env,
        problems,
        fixture_owners(modules),
    )

    if args.check:
        status = check_outputs(outputs)
        for line in summary:
            print(line)
        print("--check wrote nothing and mutated nothing")
        return status

    try:
        written = write_outputs(outputs)
    except GenerateError as exc:
        print(f"ERROR: {exc}")
        return 2

    for line in summary:
        print(line)
    print(f"wrote {len(written)} file(s) under testcases/; every case stays {DEFAULT_STATUS}")

    leftovers = stale_extras(outputs)
    if leftovers:
        print(
            f"NOTE: {len(leftovers)} generated-looking file(s) on disk are not produced by this run and "
            "were left untouched (delete or regenerate them deliberately):"
        )
        for rel in leftovers:
            print(f"  testcases/{rel}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
